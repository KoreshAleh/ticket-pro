function storedPreference<T extends string>(key: string, allowedValues: readonly T[], fallback: T): T {
    try {
        const value = localStorage.getItem(key);
        return value && allowedValues.includes(value as T) ? value as T : fallback;
    } catch (error) {
        console.error(`Could not read preference "${key}" from local storage:`, error);
        return fallback;
    }
}

export const PreferenceControls: React.FC = () => {
    const { language, theme, setLanguage, setTheme, t } = usePreferences();
    const [isOpen, setIsOpen] = useState(false);
    const controlRef = useRef<HTMLDivElement>(null);

    useEffect(() => {
        if (!isOpen) return;

        const closeOnOutsideClick = (event: PointerEvent) => {
            if (event.target instanceof Node && !controlRef.current?.contains(event.target)) {
                setIsOpen(false);
            }
        };
        const closeOnEscape = (event: KeyboardEvent) => {
            if (event.key === 'Escape') setIsOpen(false);
        };

        document.addEventListener('pointerdown', closeOnOutsideClick);
        document.addEventListener('keydown', closeOnEscape);
        return () => {
            document.removeEventListener('pointerdown', closeOnOutsideClick);
            document.removeEventListener('keydown', closeOnEscape);
        };
    }, [isOpen]);

    return (
        <div ref={controlRef} className="preferences-control">
            <button
                type="button"
                className="preferences-menu-trigger"
                aria-label={t('Display preferences')}
                aria-expanded={isOpen}
                aria-controls="preferences-menu"
                onClick={() => setIsOpen(open => !open)}
            >
                <span />
                <span />
                <span />
            </button>
            {isOpen && (
                <div id="preferences-menu" className="preferences-menu">
                    <label className="preferences-field">
                        <span>{t('Language')}</span>
                        <select
                            className="preferences-language"
                            aria-label={t('Language')}
                            value={language}
                            onChange={event => {
                                setLanguage(event.target.value as AppLanguage);
                                setIsOpen(false);
                            }}
                        >
                            <option value="en">English</option>
                            <option value="pl">Polski</option>
                            <option value="uk">Українська</option>
                            <option value="ru">Русский</option>
                        </select>
                    </label>
                    <label className="preferences-field">
                        <span>{t('Theme')}</span>
                        <select
                            className="preferences-theme"
                            aria-label={t('Theme')}
                            value={theme}
                            onChange={event => {
                                setTheme(event.target.value as AppTheme);
                                setIsOpen(false);
                            }}
                        >
                            <option value="dark">{t('Dark')}</option>
                            <option value="light">{t('Light')}</option>
                        </select>
                    </label>
                </div>
            )}
        </div>
    );
};

export const PreferencesProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [language, setLanguage] = useState<AppLanguage>(() =>
        storedPreference('ticketpro-language', ['en', 'pl', 'uk', 'ru'], 'en')
    );
    const [theme, setTheme] = useState<AppTheme>(() =>
        storedPreference('ticketpro-theme', ['dark', 'light'], 'dark')
    );

    useEffect(() => {
        document.documentElement.lang = language;
        document.documentElement.dataset.theme = theme;
        document.documentElement.style.colorScheme = theme;
    }, [language, theme]);

    useEffect(() => {
        try {
            localStorage.setItem('ticketpro-language', language);
        } catch (error) {
            console.error('Could not save language preference:', error);
        }
    }, [language]);

    useEffect(() => {
        try {
            localStorage.setItem('ticketpro-theme', theme);
        } catch (error) {
            console.error('Could not save theme preference:', error);
        }
    }, [theme]);

    const t = useCallback((text: string) => translations[language][text] ?? text, [language]);
    const value = useMemo<PreferencesContextValue>(() => ({
        language,
        theme,
        setLanguage,
        setTheme,
        t
    }), [language, theme, t]);

    return (
        <PreferencesContext.Provider value={value}>
            {children}
        </PreferencesContext.Provider>
    );
}
